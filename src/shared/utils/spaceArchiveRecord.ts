import type {
  NormalizedPersistedSpaceArchiveGitSnapshot,
  NormalizedPersistedSpaceArchiveNodeSnapshot,
  NormalizedPersistedSpaceArchiveRecord,
  NormalizedPersistedSpaceArchiveSpaceSnapshot,
  NormalizedPersistedSpaceContract,
} from '../contracts/normalizedPersistedAppState'
import type {
  PersistedSpaceArchiveAgentSnapshot,
  PersistedSpaceArchiveTaskSnapshot,
  PersistedSpaceArchiveTerminalSnapshot,
} from '../contracts/persistedAppState'
import type { NodeLabelColorOverride } from '../types/labelColor'

// Archive record builder shared by the renderer (space archive dialog) and the main process
// (space.archive on the Control Surface), so both write the same record for the same Space.
export const MAX_SPACE_ARCHIVE_RECORDS = 50

type ArchiveSpace = NormalizedPersistedSpaceContract

/** The node fields an archive snapshot reads. Renderer node data and persisted nodes both fit. */
export interface SpaceArchiveNodeSource {
  id: string
  kind: string
  title: string
  position: { x: number; y: number }
  width: number
  height: number
  labelColorOverride?: NodeLabelColorOverride
  runtimeKind?: PersistedSpaceArchiveTerminalSnapshot['runtimeKind']
  status?: PersistedSpaceArchiveAgentSnapshot['status']
  startedAt?: string | null
  endedAt?: string | null
  exitCode?: number | null
  lastError?: string | null
  executionDirectory?: string | null
  expectedDirectory?: string | null
  agent?: Partial<
    Pick<
      PersistedSpaceArchiveAgentSnapshot,
      | 'provider'
      | 'prompt'
      | 'model'
      | 'effectiveModel'
      | 'launchMode'
      | 'resumeSessionId'
      | 'resumeSessionIdVerified'
      | 'executionDirectory'
      | 'expectedDirectory'
      | 'directoryMode'
      | 'customDirectory'
      | 'shouldCreateDirectory'
      | 'taskId'
    >
  > | null
  task?: Partial<
    Pick<
      PersistedSpaceArchiveTaskSnapshot,
      | 'requirement'
      | 'status'
      | 'priority'
      | 'tags'
      | 'linkedAgentNodeId'
      | 'lastRunAt'
      | 'autoGeneratedTitle'
      | 'createdAt'
      | 'updatedAt'
    >
  > | null
  note?: { text?: string } | null
  plugin?: {
    pluginId?: string
    schemaVersion?: number
    repoPath?: string
    mountId?: string | null
  } | null
}

function normalizeOptionalString(value: unknown): string | null {
  if (typeof value !== 'string') {
    return null
  }

  const trimmed = value.trim()
  return trimmed.length > 0 ? trimmed : null
}

function toSnapshot(
  node: SpaceArchiveNodeSource,
): NormalizedPersistedSpaceArchiveNodeSnapshot | null {
  const frame = {
    position: { x: node.position.x, y: node.position.y },
    size: { width: node.width, height: node.height },
  }
  const labelColorOverride = node.labelColorOverride ?? null
  const base = { id: node.id, title: node.title, frame, labelColorOverride }

  switch (node.kind) {
    case 'terminal':
      return {
        kind: 'terminal',
        ...base,
        runtimeKind: node.runtimeKind ?? null,
        executionDirectory: normalizeOptionalString(node.executionDirectory),
        expectedDirectory: normalizeOptionalString(node.expectedDirectory),
        startedAt: node.startedAt ?? null,
        endedAt: node.endedAt ?? null,
        exitCode: node.exitCode ?? null,
        lastError: node.lastError ?? null,
      }
    case 'agent':
      return {
        kind: 'agent',
        ...base,
        status: node.status ?? null,
        provider: node.agent?.provider ?? null,
        prompt: node.agent?.prompt ?? '',
        model: node.agent?.model ?? null,
        effectiveModel: node.agent?.effectiveModel ?? null,
        launchMode: node.agent?.launchMode ?? null,
        resumeSessionId: node.agent?.resumeSessionId ?? null,
        ...(node.agent?.resumeSessionIdVerified === true
          ? { resumeSessionIdVerified: true as const }
          : {}),
        executionDirectory: normalizeOptionalString(node.agent?.executionDirectory),
        expectedDirectory: normalizeOptionalString(node.agent?.expectedDirectory),
        directoryMode: node.agent?.directoryMode ?? null,
        customDirectory: normalizeOptionalString(node.agent?.customDirectory),
        shouldCreateDirectory: node.agent?.shouldCreateDirectory === true,
        taskId: normalizeOptionalString(node.agent?.taskId),
        startedAt: node.startedAt ?? null,
        endedAt: node.endedAt ?? null,
        exitCode: node.exitCode ?? null,
        lastError: node.lastError ?? null,
      }
    case 'task':
      return {
        kind: 'task',
        ...base,
        requirement: node.task?.requirement ?? '',
        status: node.task?.status ?? 'todo',
        priority: node.task?.priority ?? 'medium',
        tags: node.task?.tags ?? [],
        linkedAgentNodeId: node.task?.linkedAgentNodeId ?? null,
        lastRunAt: node.task?.lastRunAt ?? null,
        autoGeneratedTitle: node.task?.autoGeneratedTitle === true,
        createdAt: node.task?.createdAt ?? null,
        updatedAt: node.task?.updatedAt ?? null,
      }
    case 'note':
      return { kind: 'note', ...base, text: node.note?.text ?? '' }
    case 'plugin':
      return {
        kind: 'plugin',
        ...base,
        pluginId: node.plugin?.pluginId ?? 'missing-plugin',
        schemaVersion: node.plugin?.schemaVersion ?? 1,
        repoPath: node.plugin?.repoPath ?? '',
        mountId: node.plugin?.mountId ?? null,
      }
    default:
      return null
  }
}

export function buildSpaceArchiveRecord({
  space,
  spaces,
  nodes,
  git = null,
  archivedAt = new Date().toISOString(),
  recordId = crypto.randomUUID(),
}: {
  space: ArchiveSpace
  spaces?: ArchiveSpace[]
  nodes: SpaceArchiveNodeSource[]
  git?: NormalizedPersistedSpaceArchiveGitSnapshot | null
  archivedAt?: string
  recordId?: string
}): NormalizedPersistedSpaceArchiveRecord {
  const nodeById = new Map(nodes.map(node => [node.id, node]))
  const archivedSpaces = normalizeArchivedSpaces(space, spaces)
  const archivedNodeIds = [...new Set(archivedSpaces.flatMap(candidate => candidate.nodeIds))]
  const snapshots = archivedNodeIds
    .map(nodeId => nodeById.get(nodeId))
    .filter((node): node is SpaceArchiveNodeSource => node !== undefined)
    .map(toSnapshot)
    .filter(item => item !== null)

  return {
    id: recordId,
    archivedAt,
    git,
    space: {
      id: space.id,
      name: space.name,
      directoryPath: space.directoryPath,
      labelColor: space.labelColor,
      rect: space.rect,
    },
    spaces: archivedSpaces.map(toArchiveSpaceSnapshot),
    nodes: snapshots,
  }
}

function normalizeArchivedSpaces(
  targetSpace: ArchiveSpace,
  spaces: ArchiveSpace[] | null | undefined,
): ArchiveSpace[] {
  const candidates = Array.isArray(spaces) && spaces.length > 0 ? spaces : [targetSpace]
  const result: ArchiveSpace[] = []
  const seen = new Set<string>()

  for (const candidate of [targetSpace, ...candidates]) {
    if (seen.has(candidate.id)) {
      continue
    }

    seen.add(candidate.id)
    result.push(candidate)
  }

  return result
}

function toArchiveSpaceSnapshot(space: ArchiveSpace): NormalizedPersistedSpaceArchiveSpaceSnapshot {
  return {
    id: space.id,
    name: space.name,
    directoryPath: space.directoryPath,
    targetMountId: space.targetMountId ?? null,
    parentSpaceId: space.parentSpaceId ?? null,
    boundary: space.boundary ?? null,
    labelColor: space.labelColor,
    nodeIds: [...space.nodeIds],
    rect: space.rect,
  }
}

export function appendSpaceArchiveRecord<TRecord>(previous: TRecord[], next: TRecord): TRecord[] {
  const normalized = Array.isArray(previous) ? previous : []
  return [next, ...normalized].slice(0, MAX_SPACE_ARCHIVE_RECORDS)
}
